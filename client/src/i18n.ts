export async function initializeLanguage() {
  let language = 'en'
  try {
    if (localStorage.getItem('civic-language') === 'ta') language = 'ta'
  } catch { /* The language switch also works without storage. */ }
  await i18n.use(initReactI18next).init({ lng: language, fallbackLng: 'en', resources: { en: { translation: en }, ta: { translation: ta } } })
  document.documentElement.lang = language
}
export async function selectLanguage(language: 'ta' | 'en') {
  await i18n.changeLanguage(language)
  document.documentElement.lang = language
  try { localStorage.setItem('civic-language', language) } catch { /* Language is still active for this visit. */ }
}

